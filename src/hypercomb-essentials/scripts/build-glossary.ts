// scripts/build-glossary.ts
//
// THE GLOSSARY, BAKED. documentation/glossary.md is the terminology of
// Hypercomb. The hive answers a term from its glossary tile without asking a
// model (assistant/glossary-tiles.ts), and lays those tiles out on request —
// so the browser needs the glossary's text, the way it needs the codex's.
// This writes it into one module, src/assistant/glossary.generated.ts, that is
// loaded only when the `glossary` word is said. It is NOT anatomy: nothing
// here is sent to a model (documentation/glossary-tiles.md).
//
// Deterministic on purpose: same document → same bytes. No dates, no paths,
// no environment. Runs from `prepare`, after the anatomy.

import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { glossarySource, parseGlossary } from '../src/assistant/glossary.ts'

const __dirname = dirname(fileURLToPath(import.meta.url))
const SOURCE = join(resolve(__dirname, '../../documentation'), 'glossary.md')
const OUT = resolve(__dirname, '../src/assistant/glossary.generated.ts')

if (!existsSync(SOURCE)) throw new Error('[glossary] missing documentation/glossary.md')
const source = glossarySource(readFileSync(SOURCE, 'utf8'))
const terms = parseGlossary(source).reduce((sum, section) => sum + section.terms.length, 0)
if (!terms) throw new Error('[glossary] documentation/glossary.md holds no terms (### headings under ## sections)')

const generated = `// auto-generated by scripts/build-glossary.ts — do not edit.
// Source: documentation/glossary.md

/** The glossary, as the hive reads it (assistant/glossary.ts parseGlossary). */
export const GLOSSARY_SOURCE: string = ${JSON.stringify(source)}
`

const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
if (previous !== generated) {
  const { writeFileSync } = await import('node:fs')
  writeFileSync(OUT, generated)
  console.log(`[glossary] wrote ${OUT} (${terms} terms)`)
} else {
  console.log('[glossary] unchanged')
}
